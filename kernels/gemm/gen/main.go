// Command gen emits kernels/gemm/ukernel_arm64.s: an 8×12 f32 NEON micro-kernel.
//
// The Go arm64 assembler has no by-element FMLA form, so those instructions are
// emitted as WORD with hand-encoded bits (FMLA Vd.4S, Vn.4S, Vm.S[idx]).
//
//	go run ./kernels/gemm/gen > kernels/gemm/ukernel_arm64.s
package main

import (
	"fmt"
	"os"
	"strings"
)

const (
	MR     = 8
	NR     = 12
	unroll = 4
)

// fmlaElem encodes FMLA <Vd>.4S, <Vn>.4S, <Vm>.S[idx]  (Vd += Vn * Vm[idx]).
// ARM ARM: 0 Q 0 01111 1 sz L M Rm 0001 H 0 Rn Rd ; Q=1, sz=0, index=H:L, Vm=M:Rm.
// fadd encodes FADD <Vd>.4S, <Vn>.4S, <Vm>.4S.
func fadd(d, n, m int) uint32 {
	return 0x4E20D400 | uint32(m)<<16 | uint32(n)<<5 | uint32(d)
}

func fmlaElem(rd, rn, rm, idx int) uint32 {
	l := uint32(idx & 1)
	h := uint32(idx >> 1)
	m := uint32(rm >> 4)
	rm4 := uint32(rm & 15)
	return 0x4F801000 | l<<21 | m<<20 | rm4<<16 | h<<11 | uint32(rn)<<5 | uint32(rd)
}

func main() {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f+"\n", a...) }

	acc := func(r, cc int) int { return 8 + r*3 + cc }              // V8..V31
	rowReg := func(r int) string { return fmt.Sprintf("R%d", 6+r) } // R6..R13

	w("// Code generated by kernels/gemm/gen. DO NOT EDIT.")
	w("")
	w("//go:build arm64")
	w("")
	w(`#include "textflag.h"`)
	w("")
	w("// func microKernelARM64(kc int, ap, bp []float32, c []float32, ldc int, accumulate bool)")
	w("// 8x12 tile. A panel: kc groups of 8 floats. B panel: kc groups of 12 floats.")
	w("TEXT ·microKernelARM64(SB), NOSPLIT, $0-89")
	w("\tMOVD kc+0(FP), R0")
	w("\tMOVD ap_base+8(FP), R1")
	w("\tMOVD bp_base+32(FP), R2")
	w("\tMOVD c_base+56(FP), R3")
	w("\tMOVD ldc+80(FP), R4")
	w("\tMOVBU accumulate+88(FP), R5")
	w("\tLSL $2, R4, R4 // ldc in bytes")
	w("\tMOVD R3, %s", rowReg(0))
	for r := 1; r < MR; r++ {
		w("\tADD R4, %s, %s", rowReg(r-1), rowReg(r))
	}
	// Accumulators always start at zero; when accumulating, C is added at
	// the store (C + sum) — the same grouping as the edge-tile spill and the
	// other kernels, so a row's bits cannot depend on whether it went through
	// a full panel or an edge tile (batch invariance).
	for r := 0; r < MR; r++ {
		for cc := 0; cc < 3; cc++ {
			v := acc(r, cc)
			w("\tVEOR V%d.B16, V%d.B16, V%d.B16", v, v, v)
		}
	}
	w("kloop:")
	w("\tCMP $%d, R0", unroll)
	w("\tBLT ktail")
	for u := 0; u < unroll; u++ {
		step(w, acc)
	}
	w("\tSUB $%d, R0, R0", unroll)
	w("\tB kloop")
	w("ktail:")
	w("\tCBZ R0, store")
	step(w, acc)
	w("\tSUB $1, R0, R0")
	w("\tB ktail")
	w("store:")
	w("\tCBZ R5, storeraw")
	for r := 0; r < MR; r++ {
		w("\tVLD1 (%s), [V0.S4, V1.S4, V2.S4]", rowReg(r))
		for cc := 0; cc < 3; cc++ {
			v := acc(r, cc)
			w("\tWORD $0x%08X // FADD V%d.4S, V%d.4S, V%d.4S", fadd(v, v, cc), v, v, cc)
		}
	}
	w("storeraw:")
	for r := 0; r < MR; r++ {
		w("\tVST1 [V%d.S4, V%d.S4, V%d.S4], (%s)", acc(r, 0), acc(r, 1), acc(r, 2), rowReg(r))
	}
	w("\tRET")
	os.Stdout.WriteString(b.String())
}

// step emits one k iteration: load 8 A values, 12 B values, 24 FMLAs.
func step(w func(string, ...any), acc func(r, cc int) int) {
	w("\tVLD1.P 32(R1), [V0.S4, V1.S4]")
	w("\tVLD1.P 48(R2), [V2.S4, V3.S4, V4.S4]")
	for r := 0; r < MR; r++ {
		areg, aidx := r/4, r%4
		for cc := 0; cc < 3; cc++ {
			breg := 2 + cc
			w("\tWORD $0x%08X // FMLA V%d.S4, V%d.S4, V%d.S[%d]", fmlaElem(acc(r, cc), breg, areg, aidx), acc(r, cc), breg, areg, aidx)
		}
	}
}
